const SUPPORTED_LANGUAGES = ["fr", "en", "es", "de", "it", "pt-BR"];

function normalizeLanguage(value) {
  const raw = String(value || "").trim();
  if (!raw) return "fr";
  const lower = raw.toLowerCase();

  if (lower.startsWith("pt")) return "pt-BR";
  if (lower.startsWith("fr")) return "fr";
  if (lower.startsWith("en")) return "en";
  if (lower.startsWith("es")) return "es";
  if (lower.startsWith("de")) return "de";
  if (lower.startsWith("it")) return "it";
  return "fr";
}

function getInitialLanguage() {
  const params = new URLSearchParams(window.location.search);
  const fromUrl = params.get("lang");
  if (fromUrl) return normalizeLanguage(fromUrl);

  const saved = localStorage.getItem("bloquons-language");
  if (saved) return normalizeLanguage(saved);

  return normalizeLanguage(navigator.language || navigator.userLanguage);
}

function t(key, lang = document.documentElement.lang) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.fr;
  return dict[key] ?? TRANSLATIONS.fr[key] ?? key;
}

function applyLanguage(lang, updateUrl = false) {
  lang = normalizeLanguage(lang);
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.fr;

  document.documentElement.lang = lang;
  localStorage.setItem("bloquons-language", lang);

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (!(key in dict)) return;

    if (key.startsWith("disclaimer")) {
      node.innerHTML = dict[key];
    } else {
      node.textContent = dict[key];
    }
  });

  document.title = dict.brand;
  const metaDescription = document.getElementById("metaDescription");
  if (metaDescription) metaDescription.content = dict.metaDescription;

  const ogTitle = document.getElementById("ogTitle");
  if (ogTitle) ogTitle.content = dict.brand;

  const ogDescription = document.getElementById("ogDescription");
  if (ogDescription) ogDescription.content = dict.metaDescription;

  const select = document.getElementById("languageSelect");
  if (select) select.value = lang;

  if (updateUrl) {
    const url = new URL(window.location.href);
    url.searchParams.set("lang", lang);
    history.replaceState(null, "", url);
  }

  window.dispatchEvent(new CustomEvent("bloquons-language-change", { detail: { lang } }));
}

document.addEventListener("DOMContentLoaded", () => {
  const lang = getInitialLanguage();
  applyLanguage(lang, false);

  const select = document.getElementById("languageSelect");
  if (select) {
    select.addEventListener("change", (event) => applyLanguage(event.target.value, true));
  }
});
